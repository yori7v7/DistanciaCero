import { expect, test } from '@playwright/test'
import { enableCentro, gotoApp } from './helpers'

test('la guía conserva borradores al volver y solo guarda al confirmar', async ({ page }, testInfo) => {
  test.setTimeout(120_000)
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.route(/^https?:\/\/(?!localhost(?=[:/])|127\.0\.0\.1(?=[:/]))/, route => route.abort())
  await gotoApp(page)
  await enableCentro(page)
  await page.evaluate(() => localStorage.setItem('distancia-cero-content-reasons', '[{"id":"keep","title":"Conservar"}]'))
  const form = page.getByRole('form', { name: 'Configuración guiada' })
  await page.getByRole('button', { name: 'Empezar guía', exact: true }).click()
  await form.getByLabel('Tu nombre', { exact: true }).fill('Borrador')
  await form.getByRole('button', { name: 'Siguiente', exact: true }).click()
  await expect(form.getByRole('heading', { name: 'Fechas', exact: true })).toBeFocused()
  await form.getByRole('button', { name: 'Anterior', exact: true }).click()
  await expect(form.getByLabel('Tu nombre', { exact: true })).toHaveValue('Borrador')
  page.once('dialog', dialog => dialog.dismiss())
  await form.getByRole('button', { name: 'Cancelar guía', exact: true }).click()
  await expect(form).toBeVisible()
  page.once('dialog', dialog => dialog.accept())
  await form.getByRole('button', { name: 'Cancelar guía', exact: true }).click()
  await expect(form).toHaveCount(0)
  expect(await page.evaluate(() => localStorage.getItem('distancia-cero-site-settings'))).toBeNull()

  await page.getByRole('button', { name: 'Empezar guía', exact: true }).click()
  await form.getByLabel('Tu nombre', { exact: true }).fill('Alex')
  await form.getByLabel('Nombre de tu pareja', { exact: true }).fill('Sam')
  await form.getByLabel('Nombre compartido', { exact: true }).fill('A + S')
  const today = await page.evaluate(() => {
    const now = new Date()
    return `${now.getFullYear()}-${String(now.getMonth() + 1).padStart(2, '0')}-${String(now.getDate()).padStart(2, '0')}`
  })
  await form.getByRole('button', { name: 'Siguiente', exact: true }).click()
  for (const label of ['Día en que se conocieron', 'Inicio de la relación', 'Próximo encuentro']) {
    await form.getByLabel(label, { exact: true }).fill(today)
  }
  await page.setViewportSize({ width: 390, height: 844 })
  await form.getByRole('button', { name: 'Siguiente', exact: true }).click()
  await expect(form.getByRole('heading', { name: 'Revisar', exact: true })).toBeFocused()
  await expect(form).toContainText('Alex')
  await expect(form).toContainText('Sam')
  expect(await page.evaluate(() => localStorage.getItem('distancia-cero-site-settings'))).toBeNull()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('guia-revision-movil.png') })
  await form.getByRole('button', { name: 'Guardar configuración', exact: true }).click()
  await expect(page.getByText('Configuración guardada. Tu universo ya está actualizado.', { exact: true })).toBeVisible()
  await expect(page.locator('#inicio h1')).toContainText('Sam')
  await expect(page.locator('#contador .glass-card h3')).toHaveText(['0', '1', '0', '0'])
  expect(await page.evaluate(() => localStorage.getItem('distancia-cero-content-reasons'))).toContain('Conservar')
  await page.reload({ waitUntil: 'domcontentloaded' })
  await enableCentro(page)
  await page.getByRole('button', { name: 'Revisar con la guía', exact: true }).click()
  await expect(form.getByLabel('Tu nombre', { exact: true })).toHaveValue('Alex')
  await form.getByRole('button', { name: 'Cancelar guía', exact: true }).click()
  await expect(form).toHaveCount(0)
  expect(errors).toEqual([])
})
