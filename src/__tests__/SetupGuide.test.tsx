import { act, cleanup, fireEvent, render, screen, within } from '@testing-library/react'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import SetupGuide from '../components/centro-universo/SetupGuide'
import { getSiteSettings, saveSiteSettings, SITE_SETTINGS_STORAGE_KEY } from '../services/siteSettingsService'
import { restoreContentBackup } from '../services/contentService'

beforeEach(() => localStorage.clear())
afterEach(() => { cleanup(); vi.restoreAllMocks() })

function open() {
  render(<SetupGuide />)
  fireEvent.click(screen.getByRole('button', { name: /Empezar guía|Revisar con la guía/ }))
  return screen.getByRole('form', { name: 'Configuración guiada' })
}
const change = (form: HTMLElement, label: string, value: string) => fireEvent.change(within(form).getByLabelText(label), { target: { value } })
const next = (form: HTMLElement) => fireEvent.submit(form)

describe('primera configuración guiada', () => {
  it('mantiene el borrador al volver y solo escribe al confirmar la revisión', () => {
    const form = open()
    expect(screen.getByRole('heading', { name: 'Nombres' })).toHaveFocus()
    change(form, 'Tu nombre', 'Alex')
    change(form, 'Nombre de tu pareja', 'Sam')
    next(form)
    expect(screen.getByRole('heading', { name: 'Fechas' })).toHaveFocus()
    change(form, 'Día en que se conocieron', '2025-01-02')
    fireEvent.click(within(form).getByRole('button', { name: 'Anterior' }))
    expect(within(form).getByLabelText('Tu nombre')).toHaveValue('Alex')
    next(form)
    expect(within(form).getByLabelText('Día en que se conocieron')).toHaveValue('2025-01-02')
    next(form)
    expect(screen.getByRole('heading', { name: 'Revisar' })).toHaveFocus()
    expect(within(form).getByRole('button', { name: 'Guardar configuración' })).toBeEnabled()
    expect(localStorage.getItem(SITE_SETTINGS_STORAGE_KEY)).toBeNull()
    expect(form.querySelectorAll('dt')).toHaveLength(7)
    expect(form).toHaveTextContent('Sam')
    next(form)
    expect(getSiteSettings()).toMatchObject({ couple: { yourName: 'Alex', herName: 'Sam' }, hero: { titleName: '' }, dates: { metDate: '2025-01-02' } })
    expect(screen.queryByRole('form', { name: 'Configuración guiada' })).not.toBeInTheDocument()
    expect(screen.getByRole('status')).toHaveTextContent('Configuración guardada')
    expect(screen.getByRole('button', { name: 'Revisar con la guía' })).toHaveFocus()
  })

  it('precarga ajustes existentes y conserva creaciones al guardar', () => {
    saveSiteSettings({ couple: { yourName: 'Anterior', herName: 'Sam' }, hero: { titleName: 'Mi estrella' }, dates: { relationshipStartDate: '2023-06-15' } })
    const content = '[{"id":"keep","title":"Conservar"}]'
    localStorage.setItem('distancia-cero-content-reasons', content)
    const form = open()
    expect(within(form).getByLabelText('Tu nombre')).toHaveValue('Anterior')
    expect(within(form).getByLabelText('Nombre en portada (opcional)')).toHaveValue('Mi estrella')
    change(form, 'Tu nombre', 'Nuevo')
    next(form)
    expect(within(form).getByLabelText('Inicio de la relación')).toHaveValue('2023-06-15')
    next(form)
    next(form)
    expect(getSiteSettings().couple?.yourName).toBe('Nuevo')
    expect(getSiteSettings().hero?.titleName).toBe('Mi estrella')
    expect(localStorage.getItem('distancia-cero-content-reasons')).toBe(content)
  })

  it('valida el paso actual sin escribir ni pasar con nombres o fechas inválidos', () => {
    const form = open()
    change(form, 'Nombre compartido', '   ')
    next(form)
    expect(screen.getByRole('alert')).toBeVisible()
    expect(screen.getByRole('heading', { name: 'Nombres' })).toBeVisible()
    change(form, 'Nombre compartido', 'Nosotros')
    next(form)
    change(form, 'Día en que se conocieron', '')
    next(form)
    expect(screen.getByRole('heading', { name: 'Fechas' })).toBeVisible()
    expect(screen.getByRole('alert')).toBeVisible()
    expect(localStorage.getItem(SITE_SETTINGS_STORAGE_KEY)).toBeNull()
  })

  it('cancelar conserva lo guardado y pide confirmar solo si cambió el borrador', () => {
    const confirm = vi.spyOn(window, 'confirm')
    const form = open()
    fireEvent.click(within(form).getByRole('button', { name: 'Cancelar guía' }))
    expect(confirm).not.toHaveBeenCalled()
    fireEvent.click(screen.getByRole('button', { name: 'Empezar guía' }))
    const reopened = screen.getByRole('form', { name: 'Configuración guiada' })
    change(reopened, 'Tu nombre', 'Borrador')
    confirm.mockReturnValue(false)
    fireEvent.click(within(reopened).getByRole('button', { name: 'Cancelar guía' }))
    expect(within(reopened).getByLabelText('Tu nombre')).toHaveValue('Borrador')
    confirm.mockReturnValue(true)
    fireEvent.click(within(reopened).getByRole('button', { name: 'Cancelar guía' }))
    expect(screen.queryByRole('form', { name: 'Configuración guiada' })).not.toBeInTheDocument()
    expect(localStorage.getItem(SITE_SETTINGS_STORAGE_KEY)).toBeNull()
    expect(confirm).toHaveBeenCalledTimes(2)
  })

  it('conserva el borrador ante una importación y exige cargar los nuevos ajustes', () => {
    const form = open()
    change(form, 'Tu nombre', 'Borrador')
    next(form)
    next(form)
    act(() => restoreContentBackup({ version: 2, settings: { couple: { yourName: 'Importado' } } }))
    expect(form).toHaveTextContent('Borrador')
    expect(screen.getByRole('alert')).toHaveTextContent('Hay nuevos ajustes guardados')
    expect(within(form).getByRole('button', { name: 'Guardar configuración' })).toBeDisabled()
    next(form)
    expect(getSiteSettings().couple?.yourName).toBe('Importado')
    fireEvent.click(within(form).getByRole('button', { name: 'Cargar ajustes actuales' }))
    expect(screen.getByRole('heading', { name: 'Nombres' })).toHaveFocus()
    expect(within(form).getByLabelText('Tu nombre')).toHaveValue('Importado')
  })

  it('un fallo al guardar conserva el borrador en revisión y no muestra éxito', () => {
    saveSiteSettings({ couple: { yourName: 'Guardado' } })
    const stored = localStorage.getItem(SITE_SETTINGS_STORAGE_KEY)
    const form = open()
    change(form, 'Tu nombre', 'Borrador')
    next(form)
    next(form)
    vi.spyOn(Storage.prototype, 'setItem').mockImplementation(() => { throw new DOMException('Quota', 'QuotaExceededError') })
    next(form)
    expect(screen.getByRole('alert')).toBeVisible()
    expect(screen.getByRole('heading', { name: 'Revisar' })).toBeVisible()
    expect(form).toHaveTextContent('Borrador')
    expect(localStorage.getItem(SITE_SETTINGS_STORAGE_KEY)).toBe(stored)
    expect(screen.queryByRole('status')).not.toBeInTheDocument()
    fireEvent.click(within(form).getByRole('button', { name: 'Anterior' }))
    fireEvent.click(within(form).getByRole('button', { name: 'Anterior' }))
    expect(within(form).getByLabelText('Tu nombre')).toHaveValue('Borrador')
  })
})
